test('un fallo al consultar otra fecha no muestra ni sobrescribe el cierre anterior', async ({ page, request }) => {
  const original = { timeZone: 'America/Guayaquil', worked: 'Reflexión del viernes', obstacle: '', nextStep: '', energy: null }
  await expect(await request.put('/api/daily-reviews/2026-10-09', { data: original })).toBeOK()
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Editar mi cierre', exact: true })).toBeVisible()
  await page.route('**/api/daily?**', (route) => {
    if (new URL(route.request().url()).searchParams.get('day') === '2026-10-08') {
      return route.fulfill({ status: 503, json: { error: 'No se pudo consultar el jueves.' } })
    }
    return route.continue()
  })
  await page.getByLabel('Fecha a consultar', { exact: true }).fill('2026-10-08')
  await expect(page.getByRole('alert')).toContainText('No se pudo consultar el jueves.')
  await expect(page.getByRole('region', { name: 'Cierre del día', exact: true })).not.toBeVisible()
  await page.unroute('**/api/daily?**')
  await page.getByRole('button', { name: 'Reintentar', exact: true }).click()
  await expect(page.getByLabel('Fecha a consultar', { exact: true })).toHaveValue('2026-10-08')
  await page.getByRole('button', { name: 'Revisar mi día', exact: true }).click()
  await expect(page.getByLabel('¿Qué te funcionó?', { exact: true })).toHaveValue('')
  await page.getByLabel('¿Qué te funcionó?', { exact: true }).fill('Reflexión del jueves')
  await page.getByRole('button', { name: 'Guardar mi cierre', exact: true }).click()
  await expect(page.getByText('Cierre guardado', { exact: true })).toBeVisible()
  const exported = await (await request.get('/api/export')).json()
  expect(exported.dailyReviews).toHaveLength(2)
  expect(exported.dailyReviews.find((review: { day: string }) => review.day === '2026-10-09').notes.worked).toBe(original.worked)
})

